class ListCheckpoints(ApplianceParams):
    Domain: str = Option(
        "", short="D", widget=configured("Domain"),
        help="The domain to list the checkpoints for")


@logged("mast.datapower.backups")
@cli.command('list-checkpoints', effect="read", group='checkpoints',
             exclusive=False)
def list_checkpoints(params: ListCheckpoints):
    """Lists the checkpoints which are currently in the
    specified domain"""
    logger = make_logger("mast.backups")
    env = params.environment()
    logger.info(
        "Attempting to list checkpoints for {} in {} domain".format(
            str(env.appliances), params.Domain))

    resp = env.perform_action("get_existing_checkpoints", domain=params.Domain)
    logger.debug("Responses received: {}".format(str(resp)))

    checkpoints = {}
    for host, d in list(resp.items()):
        checkpoints[host] = [
            " ".join((key, "-".join(value["date"]), ":".join(value["time"])))
            for key, value in list(d.items())]
    return ListResults(
        checkpoints, env, title="Checkpoints", suffix=params.Domain)


