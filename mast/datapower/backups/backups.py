class SetCheckpoint(ApplianceParams):
    Domain: list[str] = Option(
        default_factory=lambda: ['default'], short="D",
        widget=configured("Domain"),
        help="Domains to set checkpoints in. Use `all-domains` for "
             "every domain on the appliance. The default is the "
             "default domain.")
    comment: str = Option(
        '', short="C",
        help="The comment to use for the checkpoint (will also be used "
             "to build the checkpoint name)")
    remove_oldest: bool = Option(
        True,
        help="If specified, the oldest checkpoint will not be removed "
             "when the maximum number of checkpoints exist")


@logged("mast.datapower.backups")
@cli.command('set-checkpoint', effect="change", group='checkpoints')
def set_checkpoint(params: SetCheckpoint):
    """Sets a checkpoint in the given domains on the specified appliances"""
    logger = make_logger("mast.backups")
    env = params.environment()
    logger.info(
        "Attempting to set checkpoint on {} in {} domain(s)".format(
            str(env.appliances),
            str(params.Domain)))

    t = Timestamp()
    results = {}

    for appliance in env.appliances:
        say(appliance.hostname)
        _domains = params.Domain
        if "all-domains" in _domains:
            _domains = appliance.domains
        for domain in _domains:
            say("\t", domain)
            name = '{0}-{1}-{2}'.format(params.comment, domain, t.timestamp)
            logger.debug(
                "Attempting to set checkpoint {} on {} in {} domain".format(
                    name,
                    appliance,
                    domain))
            if params.remove_oldest:
                _max = appliance.max_checkpoints(domain)
                if len(appliance.get_existing_checkpoints(domain)) >= _max:
                    logger.info(
                        "Maximum number of checkpoints for domain "
                        "{} on {} reached. Removing oldest checkpoint.".format(
                            domain, appliance.hostname))
                    _resp = appliance.remove_oldest_checkpoint(domain)
                    logger.debug("Response received: {}".format(_resp))
            kwargs = {'domain': domain, 'ChkName': name}
            resp = appliance.SaveCheckpoint(**kwargs)
            logger.debug("Response received: {}".format(resp))
            say("\t\tSuccessful" if resp else "\t\tFailed")
            key = "{}-{}-set_checkpoint".format(appliance.hostname, domain)
            results[key] = "Succeeded" if resp else "Failed"

    report = Report(env)
    report.add(StatusResults(results), show=False)
    return report
